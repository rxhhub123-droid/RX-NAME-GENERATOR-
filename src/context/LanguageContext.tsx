interface LanguageContextType {
  currentLanguage: LanguageItem;
  setLanguage: (lang: LanguageItem) => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

const LANG_STORAGE_KEY = 'rx_ff_lang_v2';

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentLanguage, setCurrentLanguage] = useState<LanguageItem>(() => {
    try {
      const savedCode = localStorage.getItem(LANG_STORAGE_KEY);
      if (savedCode) {
        const found = LANGUAGES.find(l => l.code === savedCode);
        if (found) return found;
      }
    } catch (e) {}
    return LANGUAGES[0]; // Default: Bengali
  });

  const setLanguage = (lang: LanguageItem) => {
    setCurrentLanguage(lang);
    try {
      localStorage.setItem(LANG_STORAGE_KEY, lang.code);
      // Clean up any residual googtrans cookies to prevent browser popups
      document.cookie = 'googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;';
      if (typeof window !== 'undefined' && window.location) {
        document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; domain=${window.location.hostname}; path=/;`;
      }
    } catch (e) {}
  };

  // Safe translation helper with fallbacks
  const t = (key: string): string => {
    const langDict = TRANSLATIONS[currentLanguage.code];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    // Fallback to English if available
    if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
      return TRANSLATIONS.en[key];
    }
    // Fallback to Bengali default
    if (TRANSLATIONS.bn && TRANSLATIONS.bn[key]) {
      return TRANSLATIONS.bn[key];
    }
    return key;
  };

  return (
    <LanguageContext.Provider value={{ currentLanguage, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
